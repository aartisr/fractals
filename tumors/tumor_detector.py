def _ensure_directory_exists(directory: str) -> None:
    """
    Create directory if it doesn't exist.
    
    Args:
        directory: Path to directory to create
    
    Side Effects:
        Creates directory and parent directories as needed
    """
    try:
        os.makedirs(directory, exist_ok=True)
        logger.debug(f"Ensured directory exists: {directory}")
    except Exception as e:
        logger.error(f"Failed to create directory {directory}: {e}")


def _download_image(url: str, local_path: str) -> bool:
    """
    Download an image from URL to local path.
    
    Args:
        url: Image URL to download
        local_path: Local file path to save to
    
    Returns:
        True if download successful, False otherwise
    
    Retry Logic:
        - Attempts download up to MAX_RETRIES times
        - Uses DOWNLOAD_TIMEOUT for each attempt
        - Logs all attempts and failures
    
    Error Handling:
        - Network errors: Logged and retried
        - Timeout errors: Logged and retried
        - File write errors: Logged and failed
    """
    logger.info(f"Downloading image: {url} -> {local_path}")
    
    for attempt in range(1, MAX_RETRIES + 1):
        try:
            # Download with timeout
            urllib.request.urlretrieve(url, local_path)
            
            # Verify file was created and has content
            if os.path.exists(local_path) and os.path.getsize(local_path) > 0:
                logger.info(
                    f"Successfully downloaded: {local_path} "
                    f"({os.path.getsize(local_path)} bytes)"
                )
                return True
            else:
                logger.warning(f"Downloaded file is empty: {local_path}")
                
        except urllib.error.URLError as e:
            logger.warning(
                f"Download attempt {attempt}/{MAX_RETRIES} failed: {e}"
            )
            
        except urllib.error.HTTPError as e:
            logger.error(f"HTTP error downloading {url}: {e.code} {e.reason}")
            return False  # Don't retry HTTP errors
            
        except Exception as e:
            logger.exception(f"Unexpected error downloading {url}: {e}")
    
    logger.error(f"Failed to download after {MAX_RETRIES} attempts: {url}")
    return False


def _show_detection_error(self, idx: int, message: str) -> None:
    """
    Display detection error message in UI label.
    
    Args:
        self: UI window instance
        idx: Image slot index
        message: Error message to display
    """
    error_text = f"Detection failed:\n{message}"
    self.tumor_detected_labels[idx].setText(error_text)
    logger.error(f"Detection error for slot {idx}: {message}")


