def download_sample_images(output_dir: Optional[str] = None) -> List[str]:
    """
    Download all sample tumor detection images to a directory.
    
    Convenience function for downloading the complete sample dataset
    for demo, testing, or training purposes.
    
    Args:
        output_dir: Directory to save images (default: tumors/originals)
    
    Returns:
        List of paths to successfully downloaded images
    
    Side Effects:
        - Creates output directory if needed
        - Downloads images from SAMPLE_IMAGE_URLS
        - Logs download progress
    
    Example:
        >>> paths = download_sample_images('data/samples')
        >>> print(f"Downloaded {len(paths)} images")
    """
    if output_dir is None:
        output_dir = ORIGINALS_DIR
    
    _ensure_directory_exists(output_dir)
    
    downloaded = []
    
    for view_name, url in SAMPLE_IMAGE_URLS.items():
        filename = f"sample_{view_name}.jpg"
        local_path = os.path.join(output_dir, filename)
        
        if _download_image(url, local_path):
            downloaded.append(local_path)
    
    logger.info(
        f"Downloaded {len(downloaded)}/{len(SAMPLE_IMAGE_URLS)} sample images"
    )
    return downloaded


def get_model_path(view: str) -> str:
    """
    Get the model file path for a specific anatomical view.
    
    Args:
        view: Anatomical view name:
            - 'axial': Horizontal cross-section
            - 'coronal': Frontal plane
            - 'sagittal': Side profile
    
    Returns:
        Path to the corresponding model file
    
    Raises:
        ValueError: If view is not recognized
    
    Example:
        >>> model = get_model_path('axial')
        >>> print(model)
        tumors/output_models/tumor_detector_axial.pt
    """
    view = view.lower()
    
    model_map = {
        'axial': 'tumors/output_models/tumor_detector_axial.pt',
        'coronal': 'tumors/output_models/tumor_detector_coronal.pt',
        'sagittal': 'tumors/output_models/tumor_detector_sagittal.pt',
    }
    
    if view not in model_map:
        raise ValueError(
            f"Unknown view: {view}. "
            f"Valid options: {', '.join(model_map.keys())}"
        )
    
    return model_map[view]


def validate_model_files() -> dict:
    """
    Check if all required model files exist.
    
    Returns:
        Dictionary mapping view names to existence status:
            {'axial': True, 'coronal': False, 'sagittal': True}
    
    Example:
        >>> status = validate_model_files()
        >>> missing = [v for v, exists in status.items() if not exists]
        >>> if missing:
        ...     print(f"Missing models: {missing}")
    """
    status = {}
    
    for view in ['axial', 'coronal', 'sagittal']:
        model_path = get_model_path(view)
        status[view] = os.path.exists(model_path)
        
        if status[view]:
            logger.debug(f"Model found: {view} -> {model_path}")
        else:
            logger.warning(f"Model missing: {view} -> {model_path}")
    
    return status


