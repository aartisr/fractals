def get_tumor_detection_images() -> List[Tuple[str, str]]:
    """
    Get paths to tumor detection image pairs (original, detected).
    
    Downloads sample images if not present locally and returns paths to
    both original and detected versions for demo/testing purposes.
    
    Returns:
        List of tuples: [(original_path, detected_path), ...]
            - original_path: Local path to original medical image
            - detected_path: Expected path to detection result
    
    Side Effects:
        - Downloads images from SAMPLE_IMAGE_URLS if not present
        - Creates local files in tumors/ directory
        - Logs download progress and errors
    
    Directory Structure:
        tumors/
            original_1.jpg  # Axial view
            original_2.jpg  # Coronal view
            original_3.jpg  # Sagittal view
    
    Note:
        Detected images should be generated by the detection pipeline.
        This function only provides the expected output paths.
    
    Example:
        >>> pairs = get_tumor_detection_images()
        >>> for orig, det in pairs:
        ...     print(f"Original: {orig}, Detected: {det}")
    
    Warning:
        This function is deprecated. Use the UI handlers for production.
        Provided for backwards compatibility and demo purposes only.
    """
    logger.info("Preparing tumor detection image dataset")
    
    # Ensure tumors directory exists
    _ensure_directory_exists(TUMORS_DIR)
    
    # Download original images if not present
    local_originals = []
    urls = [
        SAMPLE_IMAGE_URLS['axial'],
        SAMPLE_IMAGE_URLS['coronal'],
        SAMPLE_IMAGE_URLS['sagittal']
    ]
    
    for idx, url in enumerate(urls, start=1):
        local_path = os.path.join(TUMORS_DIR, f'original_{idx}.jpg')
        
        if not os.path.exists(local_path):
            success = _download_image(url, local_path)
            if not success:
                logger.warning(
                    f"Failed to download image {idx}, using placeholder path"
                )
        
        local_originals.append(local_path)
    
    # Pair with expected detection output paths
    image_pairs = list(zip(local_originals, LEGACY_DETECTION_PATHS))
    
    logger.info(f"Prepared {len(image_pairs)} image pairs")
    return image_pairs


