def run_axial_detection(self) -> None:
    """
    Run tumor detection on axial view image (DEPRECATED).
    
    Legacy function for running detection on a hardcoded axial view image.
    Directly runs YOLOv5 detection and updates UI.
    
    Args:
        self: UI window instance with tumor_detected_labels attribute
    
    Side Effects:
        - Runs YOLOv5 subprocess
        - Updates self.tumor_detected_labels[0] with result
        - Shows error message in label if detection fails
    
    Deprecation:
        This function is deprecated. Use run_tumor_detection() from
        handlers module instead, which provides:
            - Multi-view support (axial/coronal/sagittal)
            - Better error handling
            - User-selected images (not hardcoded)
            - Temporary file management
            - Comprehensive logging
    
    Legacy Behavior:
        - Uses hardcoded image URL
        - Uses hardcoded model path
        - Limited error handling
        - No cleanup of temp files
    
    Example (deprecated):
        >>> run_axial_detection(window)  # Don't use this
        
    Replacement:
        >>> from tumors.handlers import run_tumor_detection
        >>> run_tumor_detection(window, idx=0)  # Use this instead
    """
    logger.warning(
        "run_axial_detection() is deprecated. "
        "Use run_tumor_detection() from handlers module."
    )
    
    # Hardcoded detection parameters (legacy)
    try:
        import yolov5
        logger.info("Running legacy axial detection using yolov5 PyPI API")
        model = yolov5.load("output_models/tumor_detector_axial.pt")
        results = model(SAMPLE_IMAGE_URLS['axial'], size=640, conf=0.4)
        results.save()
        # Detected image is saved by yolov5 API; further logic can be added here if needed
        detected_path = LEGACY_DETECTION_PATHS[0]
        
        if os.path.exists(detected_path):
            pixmap = QPixmap(detected_path)
            
            if not pixmap.isNull():
                self.tumor_detected_labels[0].setPixmap(pixmap)
                logger.info(f"Loaded detection result: {detected_path}")
            else:
                _show_detection_error(
                    self,
                    0,
                    "Failed to load detection result image"
                )
        else:
            _show_detection_error(
                self,
                0,
                "Detection output file not found"
            )
            
    except subprocess.TimeoutExpired:
        logger.error("Detection process timed out")
        _show_detection_error(self, 0, "Detection timed out after 60 seconds")
        
    except subprocess.CalledProcessError as e:
        logger.error(f"Detection subprocess failed: {e}")
        _show_detection_error(self, 0, f"Detection failed: {e}")
        
    except Exception as e:
        logger.exception("Unexpected error in legacy detection")
        _show_detection_error(self, 0, f"Error: {e}")


